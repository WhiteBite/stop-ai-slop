#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { detectCommentSlop, isGeneratedFile, profileFor } from "./scan.mjs"
import { SECURITY_RULES } from "./src/rules.mjs"

const CORPUS_PATH = fileURLToPath(new URL("../../detekt-rules/src/test/resources/parity-corpus.json", import.meta.url))

// the port is .kt-only: cases run under cfamily, CASE_FILE only feeds generated-name detection
const CASE_FILE = "Parity.kt"

const DENSE_CODE = Array.from({ length: 100 }, (_, i) => `val v${i} = ${i}`)

// expected verdicts are computed by the JS engine, never typed by hand; the Kotlin port is the side under test
export const CASES = [
  { name: "obvious-below-density", lines: ["// increment the counter", "counter += 1", ...DENSE_CODE] },
  { name: "obvious-above-density", lines: ["// increment the counter", "counter += 1", "// reset slot", "resetSlot()"] },
  { name: "directive-in-string", lines: ['val s = "stop-ai-slop-ignore-file"', "// Step 1: run", "val x = 1"] },
  { name: "generated-head-in-string", lines: ['val note = "do not edit generated files by hand"', "// Step 1: run", "val x = 1"] },
  { name: "generated-head-in-comment", lines: ["// Code generated by tool. DO NOT EDIT.", "// Step 1: run", "val x = 1"] },
  { name: "block-inline-opener", lines: ["/* Step 1 */ val x = 1"] },
  { name: "orphan-star-step", lines: ["val a = 1", " * Step 1"] },
  { name: "block-continuation-no-marker", lines: ["val x = 1 /* note", "Step 2", "*/"] },
  { name: "block-opener-star-continuation", lines: ["val x = 1 /* note", " * Step 2", " */"] },
  { name: "multi-line-run", lines: ["// first line of the run", "// second line of the run", "val x = 1"] },
  { name: "long-comment", lines: ["// " + "y".repeat(121), "val x = 1"] },
  { name: "license-header", lines: ["// Copyright (c) 2024 Foo Inc.", "// All rights reserved.", "val x = 1"] },
  { name: "ignore-next-line-inline-valid-rule", lines: ["val d = 1 // stop-ai-slop-ignore-next-line vend/step-numbered", "// Step 1: run", "val x = 1"] },
  { name: "unknown-id-line-directive-inert", lines: ["// stop-ai-slop-ignore-line bogus-id", "// было, стало", "val x = 1"] },
  { name: "unknown-id-file-directive-inert", lines: ["// stop-ai-slop-ignore-file bogus-id", "// было, стало", "val x = 1"] },
  { name: "todo-spanish-prose", lines: ["// repasa todo el inventario", "val x = 1"] },
  { name: "todo-lowercase-xxx", lines: ["// xxx", "val x = 1"] },
  { name: "step-version-prose", lines: ["// 1.0.0 is the minimum", "val x = 1"] },
  { name: "step-decimal-prose", lines: ["// 2.5x faster", "val x = 1"] },
]

const cmpStr = (a, b) => (a < b ? -1 : a > b ? 1 : 0)
const cmpFinding = (a, b) => (a.line !== b.line ? a.line - b.line : cmpStr(a.rule, b.rule))

export function buildCorpus() {
  return CASES.map((c) => {
    const text = c.lines.join("\n")
    let findings = detectCommentSlop(c.lines, profileFor(CASE_FILE), false, null, null)
    if (isGeneratedFile(CASE_FILE, text, null)) findings = findings.filter((f) => SECURITY_RULES.has(f.rule))
    const expected = findings.map((f) => ({ rule: f.rule, line: f.lineNo })).sort(cmpFinding)
    return { name: c.name, lines: c.lines, expected }
  }).sort((a, b) => cmpStr(a.name, b.name))
}

function serialize(corpus) {
  return JSON.stringify(corpus, null, 2) + "\n"
}

function reportDelta(current, next) {
  const a = current.split("\n")
  const b = next.split("\n")
  const total = Math.max(a.length, b.length)
  let shown = 0
  for (let i = 0; i < total && shown < 20; i++) {
    if (a[i] !== b[i]) {
      console.error(`line ${i + 1}:`)
      console.error(`  - ${a[i] ?? ""}`)
      console.error(`  + ${b[i] ?? ""}`)
      shown++
    }
  }
  if (total - shown > 0 && a.length !== b.length) console.error(`… ${Math.abs(a.length - b.length)} line(s) difference in length`)
}

function main(argv) {
  const next = serialize(buildCorpus())
  const mode = argv[0]
  if (mode === "--write") {
    mkdirSync(dirname(CORPUS_PATH), { recursive: true })
    writeFileSync(CORPUS_PATH, next)
    console.log(`parity: written ${CORPUS_PATH}`)
    return 0
  }
  if (mode === "--check") {
    const current = existsSync(CORPUS_PATH) ? readFileSync(CORPUS_PATH, "utf8") : ""
    if (current === next) {
      console.log("parity: in sync")
      return 0
    }
    console.error("parity: out of sync with the JS engine")
    reportDelta(current, next)
    return 1
  }
  console.error("usage: gen-parity-fixtures.mjs (--write | --check)")
  return 2
}

const isMain = (() => {
  try {
    return process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
  } catch {
    try {
      return process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href
    } catch {
      return false
    }
  }
})()
if (isMain) process.exit(main(process.argv.slice(2)))